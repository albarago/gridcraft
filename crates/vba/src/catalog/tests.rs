use super::{ExcelCatalog, parse, shipped};
use crate::analyze::{MemberCatalog, MemberStatus, Verdict, VerdictRule, analyze};
use crate::project::{VbaModule, VbaProject};
use crate::project_stream::ModuleKind;

fn status(object: Option<&str>, member: &str) -> Option<MemberStatus> {
    ExcelCatalog.status(object, member)
}

#[test]
fn shipped_file_parses_with_no_bad_rows() {
    let p = shipped();
    assert_eq!(p.bad_rows, 0);
    assert!(p.len() > 4_000, "only {} members", p.len());
    assert!(super::RAW.starts_with("# generated by cargo xtask vba-catalog from MicrosoftDocs/VBA-Docs "));
}

#[test]
fn tranche_1_members_are_planned() {
    for (object, member) in [
        ("Range", "Value"),
        ("range", "VALUE2"),
        ("Application", "ScreenUpdating"),
        ("Font", "Bold"),
        ("Interior", "Color"),
        ("Worksheet", "UsedRange"),
    ] {
        assert_eq!(status(Some(object), member), Some(MemberStatus::Planned), "{object}.{member}");
    }
}

#[test]
fn unreviewed_is_unknown_and_unlisted_is_none() {
    assert_eq!(status(Some("Application"), "VBE"), Some(MemberStatus::Unknown));
    assert_eq!(status(Some("Range"), "AutoFilter"), Some(MemberStatus::Unknown));
    assert_eq!(status(Some("Range"), "NoSuchMember"), None);
    assert_eq!(status(Some("ws"), "Range"), None, "a variable has no type yet");
    assert_eq!(status(Some("Me"), "Range"), None);
    assert_eq!(status(None, "Value"), None);
}

#[test]
fn aliases_name_the_excel_type() {
    assert_eq!(status(Some("Cells"), "Value"), Some(MemberStatus::Planned));
    assert_eq!(status(Some("ActiveCell"), "Offset"), Some(MemberStatus::Planned));
    assert_eq!(status(Some("End"), "Row"), Some(MemberStatus::Unknown), "Range.Row is unreviewed");
    assert_eq!(status(Some("ThisWorkbook"), "Save"), Some(MemberStatus::Planned));
    assert_eq!(status(Some("ActiveSheet"), "Cells"), Some(MemberStatus::Planned));
    // A collection answers for itself first, then for its item type.
    assert_eq!(status(Some("Worksheets"), "Add"), Some(MemberStatus::Planned));
    assert_eq!(status(Some("Worksheets"), "Range"), Some(MemberStatus::Planned));
    assert_eq!(status(Some("workbooks"), "SaveAs"), Some(MemberStatus::Planned));
}

#[test]
fn kinds_and_malformed_rows() {
    let text = "# header\n\
                X\tA\tmethod\t\tnone\tplanned\t\n\
                X\tA\tevent\t\tnone\tsupported\t\n\
                X\tB\tevent\t\tnone\tnotPlanned\t\n\
                X\tC\tproperty\t\t?\tunreviewed\ta note\n\
                X\tC\tmethod\t\tnone\tsupported\t\n\
                \n\
                not a row\n\
                X\tD\tgizmo\t\t\tplanned\t\n\
                X\tE\tmethod\t\tnone\tmaybe\t\n\
                \tF\tmethod\t\tnone\tplanned\t\n";
    let p = parse(text);
    assert_eq!(p.bad_rows, 4);
    assert_eq!(p.status(Some("x"), "a"), Some(MemberStatus::Planned), "the method wins over the event");
    assert_eq!(p.status(Some("X"), "B"), Some(MemberStatus::NotPlanned), "an event answers when it is the only kind");
    assert_eq!(p.status(Some("X"), "C"), Some(MemberStatus::Supported), "the best of two non-event rows");
    assert_eq!(p.status(Some("X"), "D"), None);
    assert_eq!(p.status(Some("X"), "E"), None);
    assert!(parse("").is_empty());
}

#[test]
fn analyze_with_the_shipped_catalog() {
    let source = "Sub A()\r\n  ws.Range(\"A1\").Value = 1\r\n  Application.ScreenUpdating = False\r\n  x = Application.VBE\r\nEnd Sub\r\n";
    let module = VbaModule {
        name: "M".into(),
        code_name: "M".into(),
        stream_name: "M".into(),
        kind: ModuleKind::Standard,
        text_offset: 0,
        source: source.into(),
        diagnostics: Vec::new(),
    };
    let r = analyze(&VbaProject { modules: vec![module], ..VbaProject::default() }, &ExcelCatalog);
    let got: Vec<(String, MemberStatus)> =
        r.members.iter().map(|m| (format!("{}.{}", m.object.as_deref().unwrap_or_default(), m.member), m.status)).collect();
    assert_eq!(
        got,
        [
            ("Application.ScreenUpdating".to_string(), MemberStatus::Planned),
            ("Application.VBE".to_string(), MemberStatus::Unknown),
            ("Range.Value".to_string(), MemberStatus::Planned),
            ("ws.Range".to_string(), MemberStatus::Unknown),
        ]
    );
    // Unreviewed and untyped members keep the verdict at "analysis only", never "unsupported".
    assert_eq!(r.verdict, Verdict::AnalysisOnly);
    assert!(r.reasons.iter().all(|x| x.rule == VerdictRule::MemberUnknown));
}
